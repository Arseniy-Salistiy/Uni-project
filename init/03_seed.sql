insert into grades(student_id, course_assignment_id, assignment_id, grade, graded_by)
select
    s.user_id,
    ca.id,
    a.id,
    (array[2,3,4,5])[1 + floor(random()*4)::int],
    ca.teacher_id
from students s
join course_assignments as ca on ca.group_id = s.group_id
join assignments as a on a.course_assignment_id = ca.id
where s.status = 'числится';

insert into grades(student_id, course_assignment_id, assignment_id, grade, graded_by)
select
  s.user_id,
  ca.id,
  null,
  round(avg(g.grade)::numeric, 1),
  ca.teacher_id
from students s
join course_assignments ca on ca.group_id = s.group_id
join grades g on g.student_id = s.user_id and g.course_assignment_id = ca.id
where g.assignment_id is not null
group by s.user_id, ca.id, ca.teacher_id;
